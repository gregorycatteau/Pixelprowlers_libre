const fs=require('fs'), vm=require('vm'), assert=require('assert'), path=require('path');
const code=fs.readFileSync(path.join(__dirname,'..','web','app.js'),'utf8');
const root={innerHTML:'',textContent:''};
const context={document:{addEventListener(){},getElementById(){return root;}},window:{},console,Map,Promise,Set};
vm.createContext(context);
vm.runInContext(code+`\n globalThis.__check={handleSimulation,resetSimulation,interactiveDesktop,discoveryDemo,DISCOVERY};`,context);
const api=context.__check;
api.handleSimulation('menu');
assert(api.interactiveDesktop().includes('sim-menu'));
api.handleSimulation('open:files');
assert(api.interactiveDesktop().includes('Nemo — Personnel'));
api.handleSimulation('folder:Téléchargements');
assert(api.interactiveDesktop().includes('Téléchargements est vide'));
api.handleSimulation('minimize');
assert(!api.interactiveDesktop().includes('sim-window\"'));
api.handleSimulation('restore');
assert(api.interactiveDesktop().includes('sim-window'));
api.handleSimulation('close');
assert(!api.interactiveDesktop().includes('sim-window\"'));
api.resetSimulation();
assert(!api.interactiveDesktop().includes('sim-menu'));
assert(api.discoveryDemo(api.DISCOVERY[0]).includes('Manipuler la simulation'));
console.log('PASS: 8 scénarios de simulation isolée.');
